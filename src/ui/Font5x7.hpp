inline const Glyph* findGlyph(char c) {
    for (const auto& g : kGlyphs) {
        if (g.ch == c) {
            return &g;
        }
    }
    return nullptr; // 调用方画 '?'
}

inline void drawText(FrameBuffer& fb, int x, int y, const char* s, const Color& c) {
    for (; *s != '\0'; ++s, x += kAdvance) {
        const Glyph* g = findGlyph(*s);
        static const Glyph kUnknown = {'?', {0x42, 0x43, 0x59, 0x0D, 0x03}};
        if (g == nullptr) {
            g = &kUnknown;
        }
        for (int col = 0; col < kGlyphCols; ++col) {
            const unsigned char bits = g->col[col];
            for (int row = 0; row < kGlyphRows; ++row) {
                if ((bits >> row) & 0x01) {
                    fb.putPixel(x + col, y + row, c);
                }
            }
        }
    }
}

inline int textWidth(const char* s) {
    int n = 0;
    for (; *s != '\0'; ++s) {
        ++n;
    }
    return n * kAdvance;
}

